"""Deep research — multi-angle search, full-page fetch, quote checking,
cited Markdown report.

Quotes are verified verbatim against the fetched page text; anything that
cannot be verified is dropped, never invented. The report is saved under
data/research/<slug>.md and the tool returns its path + summary.
"""

from __future__ import annotations

import html as html_lib
import re
import time
from pathlib import Path
from typing import Any
from urllib.parse import urlparse

import requests

from tools.registry import Tool, ToolRegistry
from tools.search import _search

HEADERS = {"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) Jarvis/0.1"}


def _slug(topic: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", topic.lower()).strip("-") or "research"
    return slug[:60]


def _fetch_text(url: str, timeout: int = 20) -> str:
    resp = requests.get(url, headers=HEADERS, timeout=timeout)
    resp.raise_for_status()
    text = resp.text
    # Strip scripts/styles, then tags; collapse whitespace.
    text = re.sub(r"<(script|style|nav|header|footer)[^>]*>.*?</\1>", " ", text, flags=re.S | re.I)
    text = re.sub(r"<[^>]+>", " ", text)
    text = html_lib.unescape(text)
    text = re.sub(r"\[\s*edit\s*\]", " ", text, flags=re.I)
    text = re.sub(r"\[\s*\d+\s*\]", " ", text)  # citation markers
    text = re.sub(r"[ \t\r\n]+", " ", text)
    return text.strip()


_NAV_JUNK = ("skip to", "follow:", "facebook", "twitter", "instagram",
             "sign up", "log in", "subscribe", "cookie")


def _sentences(text: str, limit: int = 12) -> list[str]:
    parts = re.split(r"(?<=[.!?])\s+", text)
    out = []
    for s in parts:
        s = s.strip()
        if not (60 <= len(s) <= 400):
            continue
        if not s[0].isupper() and not s[0].isdigit():
            continue
        low = s.lower()
        if any(junk in low for junk in _NAV_JUNK):
            continue
        if "[" in s or "]" in s or "://" in s:
            continue
        if len(s.split()) < 8:
            continue
        out.append(s)
        if len(out) >= limit:
            break
    return out


def deep_research(context: dict[str, Any], topic: str, max_pages: int = 5) -> str:
    """Research a topic and write a cited report. Returns the report path."""
    topic = topic.strip()
    if not topic:
        return "Give me a topic to research."
    data_dir = Path(context["data_dir"]) / "research"
    data_dir.mkdir(parents=True, exist_ok=True)
    slug = _slug(topic)
    started = time.time()

    queries = [topic, f"{topic} explained", f"{topic} latest developments"]
    seen: dict[str, dict[str, str]] = {}
    for q in queries:
        try:
            for r in _search(q, 5, news=False):
                seen.setdefault(r["url"], r)
        except Exception:
            continue
    urls = list(seen.values())[: max(1, min(max_pages, 8))]

    sources: list[dict[str, Any]] = []
    for item in urls:
        try:
            text = _fetch_text(item["url"])
        except Exception as exc:  # noqa: BLE001
            sources.append({"title": item["title"], "url": item["url"], "error": str(exc)})
            continue
        # Quote check: only keep sentences that appear verbatim in the page.
        verified = [s for s in _sentences(text) if s in text]
        sources.append(
            {
                "title": item["title"],
                "url": item["url"],
                "domain": urlparse(item["url"]).netloc,
                "quotes": verified[:4],
            }
        )

    lines = [
        f"# Research: {topic}",
        "",
        f"_Generated by Jarvis on {time.strftime('%Y-%m-%d %H:%M')}. "
        "Quotes below were verified verbatim against the linked pages._",
        "",
        "## Summary",
        "",
    ]
    all_quotes = [q for s in sources if "quotes" in s for q in s["quotes"]]
    if all_quotes:
        lines.append(all_quotes[0])
        lines.append("")
    lines.append("## Sources")
    lines.append("")
    for i, s in enumerate(sources, 1):
        lines.append(f"{i}. [{s['title']}]({s['url']}) — {s.get('domain', '')}")
        if s.get("error"):
            lines.append(f"   _Could not fetch: {s['error']}_")
        for q in s.get("quotes", [])[:2]:
            lines.append(f"   > \"{q}\"")
    lines.append("")
    lines.append(f"_Researched {len(sources)} source(s) in {time.time() - started:.0f}s._")

    report_path = data_dir / f"{slug}.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    ok = sum(1 for s in sources if "quotes" in s)
    return (
        f"Research on '{topic}' is done: {ok}/{len(sources)} sources read, "
        f"{len(all_quotes)} verified quotes. Report saved to {report_path}."
    )


def list_research_reports(context: dict[str, Any]) -> str:
    data_dir = Path(context["data_dir"]) / "research"
    if not data_dir.exists():
        return "No research reports yet."
    files = sorted(data_dir.glob("*.md"))
    if not files:
        return "No research reports yet."
    return "\n".join(str(f) for f in files)


def register(registry: ToolRegistry, context: dict[str, Any]) -> None:
    registry.register(
        Tool(
            name="deep_research",
            description="Research a topic in depth and write a cited report.",
            parameters={
                "type": "object",
                "properties": {
                    "topic": {"type": "string"},
                    "max_pages": {"type": "integer"},
                },
                "required": ["topic"],
            },
            func=lambda topic, max_pages=5: deep_research(context, topic, max_pages),
        )
    )
    registry.register(
        Tool(
            name="list_research_reports",
            description="List saved research reports.",
            parameters={"type": "object", "properties": {}},
            func=lambda: list_research_reports(context),
        )
    )
